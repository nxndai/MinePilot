  let language = 'zh-CN';
  let observer = null;

  function hasChinese(value) {
    return /[\u3400-\u9fff]/.test(value);
  }

  function polishEnglish(value) {
    return String(value)
      .replace(/（/g, ' (')
      .replace(/）/g, ') ')
      .replace(/，/g, ', ')
      .replace(/：/g, ': ')
      .replace(/\s+([,:;!?])/g, '$1')
      .replace(/\s{2,}/g, ' ');
  }

  function translate(value) {
    if (language !== 'en-US' || !value) return value;
    const text = String(value);
    if (!hasChinese(text)) return text;
    const trimmed = text.trim();
    if (!trimmed) return text;
    if (Object.prototype.hasOwnProperty.call(EN, trimmed)) {
      return polishEnglish(text.replace(trimmed, EN[trimmed]));
    }
    for (const [pattern, replacement] of PATTERNS) {
      if (pattern.test(trimmed)) {
        return polishEnglish(text.replace(trimmed, trimmed.replace(pattern, replacement)));
      }
    }
    return text;
  }

  function skipNode(node) {
    const parent = node.nodeType === 1 ? node : node.parentElement;
    if (!parent || !parent.closest) return true;
    if (parent.closest('script, style, textarea, pre, code, [data-no-i18n], #log-content, #diag-log, #toast-root')) return true;
    if (parent.closest('svg')) return true;
    return false;
  }

  function translateTextNode(node) {
    if (!node || node.nodeType !== 3 || skipNode(node)) return;
    const parent = node.parentElement;
    const trimmed = node.nodeValue.trim();
    if (language === 'en-US' && PUNCTUATION[trimmed] && node.nodeValue.length === trimmed.length) {
      node.nodeValue = PUNCTUATION[trimmed];
      return;
    }
    // “启动”在侧边导航表示首页，在版本卡片中表示启动游戏。
    if (language === 'en-US' && node.nodeValue.trim() === '启动' && parent &&
        parent.closest('.nav-item[data-view="home"]')) {
      const leading = node.nodeValue.match(/^\s*/)[0];
      const trailing = node.nodeValue.match(/\s*$/)[0];
      node.nodeValue = `${leading}Home${trailing}`;
      return;
    }
    const next = translate(node.nodeValue);
    if (next !== node.nodeValue) node.nodeValue = next;
  }

  function translateHtml(root) {
    if (!root || !root.querySelectorAll) return;
    const nodes = root.hasAttribute && root.hasAttribute('data-i18n-html')
      ? [root, ...root.querySelectorAll('[data-i18n-html]')]
      : [...root.querySelectorAll('[data-i18n-html]')];
    for (const element of nodes) {
      const key = element.getAttribute('data-i18n-html');
      const html = EN_HTML[key];
      if (html && element.innerHTML !== html) element.innerHTML = html;
    }
  }

  function translateAttribute(element, attr) {
    if (!element || element.nodeType !== 1 || skipNode(element)) return;
    if (!element.hasAttribute(attr)) return;
    if (attr === 'value' && element.tagName !== 'INPUT') return;
    const current = element.getAttribute(attr);
    const next = translate(current);
    if (next !== current) element.setAttribute(attr, next);
  }

  function translateElement(root) {
    if (!root || language !== 'en-US') return;
    if (root.nodeType === 3) {
      translateTextNode(root);
      return;
    }
    if (root.nodeType !== 1 && root.nodeType !== 9) return;
    if (root.nodeType === 1 && skipNode(root)) return;

    const textNodes = [];
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    let node = walker.nextNode();
    while (node) {
      textNodes.push(node);
      node = walker.nextNode();
    }
    for (const item of textNodes) translateTextNode(item);

    const elements = root.querySelectorAll ? [root, ...root.querySelectorAll('[title], [placeholder], [aria-label], input[type="button"]')] : [root];
    for (const element of elements) {
      if (!element || element.nodeType !== 1 || skipNode(element)) continue;
      for (const attr of ['title', 'placeholder', 'aria-label', 'value']) {
        translateAttribute(element, attr);
      }
    }
    translateHtml(root);
  }

  function startObserver() {
    if (observer || !document.body) return;
    observer = new MutationObserver((mutations) => {
      if (language !== 'en-US') return;
      for (const mutation of mutations) {
        if (mutation.type === 'attributes') {
          if (mutation.attributeName) translateAttribute(mutation.target, mutation.attributeName);
          continue;
        }
        if (mutation.type === 'characterData') {
          translateTextNode(mutation.target);
          continue;
        }
        for (const node of mutation.addedNodes) {
          if (node.nodeType === 1 || node.nodeType === 3) translateElement(node);
        }
      }
    });
    observer.observe(document.body, {
      childList: true,
      subtree: true,
      characterData: true,
      attributes: true,
      attributeFilter: ['title', 'placeholder', 'aria-label'],
    });
  }

  function apply(nextLanguage) {
    if (nextLanguage) language = nextLanguage === 'en-US' ? 'en-US' : 'zh-CN';
    document.documentElement.lang = language === 'en-US' ? 'en' : 'zh-CN';
    if (language !== 'en-US') return;
    translateElement(document.body);
    startObserver();
  }

  MP.i18n = {
    get language() { return language; },
    t: translate,
    apply,
  };
  MP.t = translate;
